def _make_grid_nodes(map_id, center_lat, center_lng, dlat=0.0018, dlng=0.0024):
    """生成基于 3x3 网格 + 挂载节点的道路图"""
    nodes = []
    nid = {"c": 0}

    def add_node(name, node_type, subtype, lat, lng):
        prefix = map_id.replace("MAP_", "").replace("_", "")[:3]
        nid["c"] += 1
        nodes.append({
            "id": f"NODE_{prefix}_{nid['c']:03d}",
            "map_id": map_id,
            "name": name,
            "type": node_type,
            "subtype": subtype,
            "latitude": round(lat, 6),
            "longitude": round(lng, 6)
        })
        return nodes[-1]["id"]

    # Grid intersections (3x3 = 9 points), with some jitter
    grid = {}
    for r in range(3):
        for c in range(3):
            lat = center_lat + (r - 1) * dlat + random.uniform(-0.0001, 0.0001)
            lng = center_lng + (c - 1) * dlng + random.uniform(-0.0001, 0.0001)
            grid[(r, c)] = add_node(
                f"路口-({r},{c})", "intersection",
                "crossroad" if r == 1 and c == 1 else "junction",
                lat, lng
            )

    # Gates at edges
    gates = {}
    gates["N"] = add_node("北门", "gate", None, center_lat + dlat * 1.8, center_lng)
    gates["S"] = add_node("南门", "gate", None, center_lat - dlat * 1.8, center_lng)
    gates["W"] = add_node("西门", "gate", None, center_lat, center_lng - dlng * 1.8)
    gates["E"] = add_node("东门", "gate", None, center_lat, center_lng + dlng * 1.8)

    return nodes, grid, gates, nid, add_node


